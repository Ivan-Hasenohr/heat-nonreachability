% Certify a target whose first six modes match a known reachable state.
% Place this directory in paper-cap/examples/heat_projected_target.
% Only the existing initializer and scalar verifier are called.

project_root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
assert(isfolder(fullfile(project_root,'src')), ...
    'Place this directory in paper-cap/examples/heat_projected_target.');
addpath(genpath(fullfile(project_root,'src')));

if ~isfolder(fullfile(project_root,'results'))
    mkdir(fullfile(project_root,'results'));
end

%% Discretization and exact target parameters
Nx = 2000;
Nt = 1200000;
T = intval(13)/100;
level = intval(3)/4; % The interval [37/50,19/25] has also been validated.
args = init_heat_fem(Nx,Nt,T,false);

% P6 of the endpoint generated by the admissible constant control u=level.
modes = intval((1:6)');
P = intval('pi');
cosine_difference = cos(P*modes/5)-cos(2*P*modes/5) ...
    +cos(4*P*modes/5)-cos(P*modes);
y_f_base = 2*level*cosine_difference ...
    .*(1-exp(-(P*modes).^2*T))./(P*modes).^3;
y_f_base(5) = intval(0); % Exact identity for the chosen control intervals.

assert(length(y_f_base) ~= Nx-1 && length(y_f_base) ~= 2*Nx, ...
    'The target must be interpreted as six sine coefficients.');
y_0 = zeros(Nx-1,1);

%% Prepare fixed nodal values from the archived finite-sine witness
data = load(fullfile(project_root,'data','witnesses','heat_projected_sine.mat'));
coefficients = data.sine_coefficients(:);
x = (1:Nx-1)'/Nx;
p = sin(pi*x*(1:length(coefficients)))*coefficients;
p = p/(norm(p)*sqrt(1/Nx));

%% Run the unchanged scalar certificate
started = tic;
[certified,J,support,pairing,err,bounds] = ...
    certify_heat_nonreachability(p,y_0,y_f_base,args);
seconds = toc(started);

case_name = 'heat_projected';
T = args{1};
Nt = args{2};
Nx = args{11};
kappa = args{12};
control_intervals = args{13};
control_bounds = [intval(0),args{9}];

save(fullfile(project_root,'results',[case_name '.mat']), ...
    'p','coefficients','y_0','y_f_base','args','level', ...
    'certified','J','support','pairing','err','bounds','seconds', ...
    'T','Nt','Nx','kappa','control_intervals','control_bounds');

disp('Certified non-reachability:');
disp(certified);
disp('Final certification enclosure:');
disp(J);
disp('Certification time in seconds:');
disp(seconds);
